const texts: Record<Locale, Text> = { fr, en, zh, hi, ar };

export const textFor = (locale: Locale) => (key: keyof Text, vars: Record<string, string> = {}) =>
  texts[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? `{${name}}`);

/** The app's words in the page's language. */
export const useText = () => textFor(useI18n().locale);
